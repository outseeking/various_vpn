/// Что умеет платформа, на которой мы сейчас запущены.
///
/// Отвечать на это прямо в экранах через `Platform.isAndroid` — плохо по двум
/// причинам. Во-первых, проверка платформы ничего не сообщает о ПРИЧИНЕ: через
/// полгода непонятно, это про запрет системы или про недоделанную функцию.
/// Во-вторых, в вебе `Platform` кидает исключение, а предпросмотр интерфейса
/// собирается именно под веб.
///
/// Поэтому здесь не «какая система», а «что доступно» — с объяснением, почему.
library;

import 'package:flutter/foundation.dart';

class Caps {
  Caps._();

  /// Разделение по приложениям (какое приложение идёт через VPN, какое мимо).
  ///
  /// На iOS невозможно в принципе: обычному приложению система не даёт ни
  /// списка установленных программ, ни выборочной маршрутизации — туннель
  /// всегда общий. Это ограничение Apple, а не недоделка.
  static bool get perAppRouting =>
      !kIsWeb && defaultTargetPlatform == TargetPlatform.android;

  /// Переход в системные настройки VPN (для «постоянного VPN» и kill switch).
  ///
  /// Открывается intent'ом Android. В iOS такого адреса нет — там роль
  /// kill switch играют правила «по требованию» внутри самого профиля VPN.
  static bool get systemVpnSettings =>
      !kIsWeb && defaultTargetPlatform == TargetPlatform.android;

  /// Смена значка приложения.
  ///
  /// Обе системы умеют, но по-разному: на Android подменяется activity-alias,
  /// на iOS система берёт готовый файл из бандла по имени (см. AltIcons и
  /// CFBundleAlternateIcons в Info.plist). Работает и там, и там.
  static bool get appIconSwitch =>
      !kIsWeb &&
      (defaultTargetPlatform == TargetPlatform.android ||
          defaultTargetPlatform == TargetPlatform.iOS);

  /// Можно ли заглядывать в буфер обмена без просьбы.
  ///
  /// На Android это незаметно и полезно: человек вернулся из бота с
  /// идентификатором, и приложение сразу предлагает войти одним нажатием.
  ///
  /// На iOS так делать нельзя. Система показывает поверх экрана свою плашку
  /// «Various VPN вставил из…» — при каждом возврате в приложение, даже если
  /// человек ничего не копировал и никуда не нажимал. Выглядит это как будто
  /// приложение лезет не в своё дело, и по сути так и есть. Вставка там
  /// остаётся, но по кнопке.
  static bool get clipboardSniff =>
      !kIsWeb && defaultTargetPlatform == TargetPlatform.android;

  /// Отключение экономии батареи для приложения.
  ///
  /// Спрашивается системным запросом Android. На iOS такого понятия нет:
  /// приложение там усыпляют всегда, а связь держит расширение туннеля — оно
  /// живёт отдельно от приложения и в экономию не попадает. Показывать эту
  /// настройку там значило бы обещать управление тем, чего нет.
  static bool get batteryOptimization =>
      !kIsWeb && defaultTargetPlatform == TargetPlatform.android;

  /// Доступны ли списки geosite/geoip прямо в ядре.
  ///
  /// На Android они лежат внутри самого ядра (geosite.dat и geoip.dat в AAR).
  /// На iOS те же файлы кладутся в ресурсы расширения на сборке, а перед
  /// стартом ядра каталог с ними объявляется через XRAY_LOCATION_ASSET
  /// (LibXrayBridge.setupAssets).
  ///
  /// Проверка осталась не на всякий случай: в вебе ядра нет вовсе, а без
  /// списков Xray не «пропускает» правило, а отказывается стартовать целиком —
  /// то есть ошибка выглядела бы как «VPN просто не включается».
  static bool get geoAssets =>
      !kIsWeb &&
      (defaultTargetPlatform == TargetPlatform.android ||
          defaultTargetPlatform == TargetPlatform.iOS);

  /// Настоящий VPN-туннель.
  ///
  /// В браузере его нет и быть не может: страница не имеет доступа к сетевому
  /// стеку устройства. Предпросмотр интерфейса от этого не страдает.
  static bool get vpnTunnel => !kIsWeb;
}
