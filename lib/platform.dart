/// Что умеет платформа, на которой мы сейчас запущены.
///
/// Отвечать на это прямо в экранах через `Platform.isAndroid` — плохо по двум
/// причинам. Во-первых, проверка платформы ничего не сообщает о ПРИЧИНЕ: через
/// полгода непонятно, это про запрет системы или про недоделанную функцию.
/// Во-вторых, в вебе `Platform` кидает исключение, а предпросмотр интерфейса
/// собирается именно под веб.
///
/// Поэтому здесь не «какая система», а «что доступно» — с объяснением, почему.
library;

import 'package:flutter/foundation.dart';

class Caps {
  Caps._();

  /// Разделение по приложениям (какое приложение идёт через VPN, какое мимо).
  ///
  /// На iOS невозможно в принципе: обычному приложению система не даёт ни
  /// списка установленных программ, ни выборочной маршрутизации — туннель
  /// всегда общий. Это ограничение Apple, а не недоделка.
  static bool get perAppRouting =>
      !kIsWeb && defaultTargetPlatform == TargetPlatform.android;

  /// Переход в системные настройки VPN (для «постоянного VPN» и kill switch).
  ///
  /// Открывается intent'ом Android. В iOS такого адреса нет — там роль
  /// kill switch играют правила «по требованию» внутри самого профиля VPN.
  static bool get systemVpnSettings =>
      !kIsWeb && defaultTargetPlatform == TargetPlatform.android;

  /// Смена значка приложения.
  ///
  /// Обе системы умеют, но по-разному: на Android это подмена activity-alias,
  /// на iOS — штатный alternate icon. Сейчас реализован только Android.
  static bool get appIconSwitch =>
      !kIsWeb && defaultTargetPlatform == TargetPlatform.android;

  /// Доступны ли списки geosite/geoip прямо в ядре.
  ///
  /// На Android они лежат внутри самого ядра (geosite.dat и geoip.dat в AAR).
  /// На iOS ядро подключается отдельно, и файлы туда надо класть руками — пока
  /// этого не сделано, ссылок на списки в конфиге быть не должно: Xray не
  /// пропускает неизвестный список, а отказывается стартовать.
  static bool get geoAssets =>
      !kIsWeb && defaultTargetPlatform == TargetPlatform.android;

  /// Настоящий VPN-туннель.
  ///
  /// В браузере его нет и быть не может: страница не имеет доступа к сетевому
  /// стеку устройства. Предпросмотр интерфейса от этого не страдает.
  static bool get vpnTunnel => !kIsWeb;
}
