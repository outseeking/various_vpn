/// Внешние ссылки бренда Various VPN. Если хэндл канала другой — поправь здесь.
library;

class Brand {
  Brand._();
  static const bot = 'https://t.me/variousvpnbot';
  static const channel =
      'https://t.me/variousvpn'; // новостной канал (уточнить)
  static const support = 'https://t.me/variousvpnbot'; // поддержка через бота

  /// Базовый адрес админ-панели (статус подписки, стрик, поддержка, цены).
  /// Домен с валидным Let's Encrypt TLS (nginx → панель), без голого IP.
  /// База API панели.
  ///
  /// Указывает на РАБОЧИЙ сервер. Прежний хост (panel.ug-connect.site) не
  /// отвечает на уровне сети, и каждый запрос к нему висел до таймаута —
  /// приложение подтормаживало на ровном месте. Сама панель на этом сервере
  /// должна быть развёрнута отдельно: смена адреса её туда не переносит.
  static const panelBase = 'https://nl1.ug-connect.site:8088';

  /// Домен-субсервер с валидным TLS: персональная подписка по ID — /vsub/{id}.
  /// Совпадает с SUB_DOMAIN_URL бота (ссылка в «Подключить» из бота).
  static const subDomain = 'https://nl1.ug-connect.site:8088';
  static String subForId(String id) => '$subDomain/vsub/$id';

  /// ОБЩИЙ список серверов берём с СУБСЕРВЕРА, а не напрямую с панели.
  ///
  /// Панель — единственная точка, падение которой раньше валило всё: список
  /// серверов не приходил, запросы висели до таймаута, а приложение оставалось
  /// со старыми (уже мёртвыми) серверами. Субсервер к панели ходит сам, держит
  /// последний удачный список на диске и умеет собрать его напрямую с живых
  /// узлов. Для приложения это означает: список приходит всегда и быстро.
  static const panelSub = '$subDomain/vsub';

  /// Единый домен нашей инфраструктуры. Все наши серверы и ссылки-подписки
  /// оканчиваются на него (nl1.ug-connect.site, panel.ug-connect.site, …).
  /// Используется, чтобы в приложение нельзя было добавить подписку чужого VPN.
  static const rootDomain = 'ug-connect.site';
}
